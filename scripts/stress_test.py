#!/usr/bin/env python3
"""Record and inspect conditional decision reviews; never choose for the owner."""
import argparse
import copy
from datetime import datetime, timezone
import json
from pathlib import Path
import sys


def nonempty(value):
    return isinstance(value, str) and bool(value.strip())


def strings(value):
    return isinstance(value, list) and all(nonempty(v) for v in value)


def validate_fields(project):
    reviews = project.get('decision_stress_tests', [])
    if not isinstance(reviews, list):
        return ['decision_stress_tests must be an array']
    errors, review_ids = [], set()
    for review in reviews:
        if not isinstance(review, dict):
            errors.append('Stress review must be an object')
            continue
        rid = review.get('review_id')
        if not nonempty(rid) or rid in review_ids:
            errors.append('Stress review_id must be unique nonempty text')
        if nonempty(rid):
            review_ids.add(rid)
        prefix = 'Stress ' + str(rid) + ': '
        def error(message):
            errors.append(prefix + message)
        if type(review.get('schema_version')) is not int or review['schema_version'] != 1:
            error('schema_version must be 1')
        for key in ('reviewer', 'strongest_objection', 'reversal_condition', 'limitations'):
            if not nonempty(review.get(key)):
                error('needs ' + key)
        baseline = review.get('baseline')
        if not isinstance(baseline, dict):
            error('needs a baseline generated by prepare')
            continue
        # Historical versions retain their own IDs; compare only their shape here.
        if baseline.get('project_id') != project.get('project_id'):
            error('baseline belongs to another project')
        digest = baseline.get('state_hash')
        if not isinstance(digest, str) or len(digest) != 64 or any(c not in '0123456789abcdef' for c in digest):
            error('baseline state_hash must be SHA-256')
        original = baseline.get('recommended_option_id')
        if 'recommended_option_id' not in baseline:
            error('baseline must explicitly record recommended_option_id, including null when absent')
        snapshot = baseline.get('snapshot')
        if not isinstance(snapshot, dict) or not strings(snapshot.get('constraints')) or not nonempty(snapshot.get('objective')):
            error('baseline snapshot needs objective and constraints')
        for field in ('option_ids', 'evidence_ids', 'source_ids'):
            if not strings(baseline.get(field)):
                error('baseline needs ' + field)
        source_content = baseline.get('source_content')
        if not isinstance(source_content, dict) or any(not nonempty(k) or not nonempty(v) for k, v in source_content.items()):
            error('baseline needs source_content fingerprints')
        old_options = set(baseline['option_ids']) if strings(baseline.get('option_ids')) else set()
        old_evidence = set(baseline['evidence_ids']) if strings(baseline.get('evidence_ids')) else set()
        old_sources = set(baseline['source_ids']) if strings(baseline.get('source_ids')) else set()
        if original is not None and (not nonempty(original) or original not in old_options):
            error('original recommendation must exist in baseline options')
        # Refer to the historical namespace, so retiring an object does not destroy history.
        def refs(obj, key, allowed, required=False):
            value = obj.get(key)
            if not strings(value) or len(value) != len(set(value)) or (required and not value):
                error(key + ' must be a list of distinct IDs' + (' (nonempty)' if required else ''))
            elif not set(value) <= allowed:
                error(key + ' references unknown baseline IDs')
        assumptions = review.get('assumptions')
        if not isinstance(assumptions, list) or not assumptions:
            error('needs key assumptions')
            assumptions = []
        aids = set()
        assumption_options = {}
        for item in assumptions:
            if not isinstance(item, dict):
                error('assumption must be an object')
                continue
            aid = item.get('assumption_id')
            if not nonempty(aid) or aid in aids:
                error('assumption_id must be unique')
            if nonempty(aid):
                aids.add(aid)
            for key in ('statement', 'verification_needed'):
                if not nonempty(item.get(key)):
                    error('assumption needs ' + key)
            if item.get('basis') not in ('hypothesis', 'recorded_evidence', 'unknown'):
                error('assumption basis must be hypothesis/recorded_evidence/unknown')
            refs(item, 'evidence_ids', old_evidence, item.get('basis') == 'recorded_evidence')
            refs(item, 'option_ids', old_options, True)
            if nonempty(aid) and strings(item.get('option_ids')):
                assumption_options[aid] = set(item['option_ids'])
        scenarios = review.get('scenarios')
        if not isinstance(scenarios, list) or len(scenarios) < 2:
            error('needs at least two substantive adverse scenarios')
            scenarios = []
        sids = set()
        for scenario in scenarios:
            if not isinstance(scenario, dict):
                error('scenario must be an object')
                continue
            sid = scenario.get('scenario_id')
            if not nonempty(sid) or sid in sids:
                error('scenario_id must be unique')
            if nonempty(sid):
                sids.add(sid)
            for key in ('title', 'premise', 'new_data_needed', 'review_trigger'):
                if not nonempty(scenario.get(key)):
                    error('scenario needs ' + key)
            if scenario.get('premise_status') not in ('hypothetical', 'observed'):
                error('premise_status must be hypothetical/observed')
            refs(scenario, 'assumption_ids', aids, True)
            refs(scenario, 'evidence_ids', old_evidence, scenario.get('premise_status') == 'observed')
            refs(scenario, 'changed_source_ids', old_sources)
            refs(scenario, 'changed_evidence_ids', old_evidence)
            changes = scenario.get('constraint_changes')
            if not isinstance(changes, list):
                error('constraint_changes must be an array')
            else:
                for change in changes:
                    if not isinstance(change, dict) or not all(nonempty(change.get(k)) for k in ('before', 'after')):
                        error('constraint change needs before/after text')
                    elif not isinstance(snapshot, dict) or not strings(snapshot.get('constraints')) or change['before'] not in snapshot['constraints']:
                        error('constraint change must name an existing baseline constraint')
                    elif change['before'] == change['after']:
                        error('constraint change must change the constraint')
            impacts = scenario.get('option_impacts')
            if not isinstance(impacts, list):
                error('needs option_impacts for every baseline option')
                impacts = []
            seen, preferred = set(), []
            for impact in impacts:
                if not isinstance(impact, dict):
                    error('option impact must be an object')
                    continue
                oid = impact.get('option_id')
                if not nonempty(oid) or oid not in old_options or oid in seen:
                    error('option impact needs a distinct baseline option_id')
                if nonempty(oid):
                    seen.add(oid)
                if impact.get('feasibility') not in ('feasible', 'infeasible', 'uncertain'):
                    error('feasibility must be feasible/infeasible/uncertain')
                if impact.get('preference') not in ('preferred', 'not_preferred', 'undetermined'):
                    error('preference must be preferred/not_preferred/undetermined')
                if impact.get('preference') == 'preferred':
                    preferred.append(oid)
                    if impact.get('feasibility') != 'feasible':
                        error('a preferred option must be feasible under the scenario premise')
                if not nonempty(impact.get('reason')):
                    error('each impact needs a reason')
                refs(impact, 'evidence_ids', old_evidence)
                if 'provisional_assessment' in impact:
                    estimate = impact['provisional_assessment']
                    if not isinstance(estimate, dict):
                        error('provisional_assessment must be an explicit conditional estimate')
                    else:
                        if set(estimate) != {'verdict', 'assumption_ids', 'rationale', 'check_next'}:
                            error('provisional assessment needs verdict, assumption_ids, rationale and check_next only')
                        if estimate.get('verdict') not in ('likely_feasible', 'likely_infeasible', 'undetermined'):
                            error('provisional verdict must be likely_feasible/likely_infeasible/undetermined')
                        if impact.get('feasibility') != 'uncertain':
                            error('provisional assessment supplements uncertain feasibility; it cannot override a recorded outcome')
                        for key in ('rationale', 'check_next'):
                            if not nonempty(estimate.get(key)): error('provisional assessment needs ' + key)
                        refs(estimate, 'assumption_ids', aids, True)
                        if strings(estimate.get('assumption_ids')) and strings(scenario.get('assumption_ids')):
                            for aid in estimate['assumption_ids']:
                                if aid not in scenario['assumption_ids'] or oid not in assumption_options.get(aid, set()):
                                    error('provisional assumptions must belong to this scenario and cover this option')
            if seen != old_options:
                error('compare every baseline option exactly once')
            decision = scenario.get('recommendation')
            if not isinstance(decision, dict):
                error('scenario needs recommendation')
                continue
            if decision.get('outcome') not in ('keep', 'switch', 'conditional_option', 'insufficient_evidence'):
                error('outcome must be keep/switch/conditional_option/insufficient_evidence')
            if original is None and decision.get('outcome') in ('keep', 'switch'):
                error('keep/switch requires a baseline recommendation')
            if original is not None and decision.get('outcome') == 'conditional_option':
                error('conditional_option requires no baseline recommendation; use keep/switch for comparison')
            if not nonempty(decision.get('rationale')):
                error('recommendation needs rationale, including for keep')
            refs(decision, 'evidence_ids', old_evidence, decision.get('outcome') in ('keep', 'switch', 'conditional_option'))
            oid = decision.get('option_id')
            if decision.get('outcome') == 'insufficient_evidence':
                if oid is not None or preferred:
                    error('insufficient_evidence cannot assert a preferred option')
            else:
                if preferred != [oid] or oid not in old_options:
                    error('recommendation must match the sole feasible preferred option')
                if decision.get('outcome') == 'keep' and oid != original:
                    error('keep must retain the original recommendation')
                if decision.get('outcome') == 'switch' and oid == original:
                    error('switch must select a different option')
    return errors


def baseline(project, path, root, *, include_feasibility=True):
    from quality import state_hash
    from material_changes import source_version
    # A review cannot invalidate its own baseline by being appended. Strategy review,
    # dates and checkpoints are already excluded by the existing hash mechanism.
    state = {k: v for k, v in project.items() if k not in
             ('decision_stress_tests', 'marketing_claims_audits', 'research_selection_reviews', 'feasibility_reviews')}
    if include_feasibility and project.get('feasibility_reviews'):
        # Work/capacity/calendar inputs can change without editing a source file.
        # Other reviews depend on these inputs, not on review IDs or timestamps.
        latest = project['feasibility_reviews'][-1]
        state['feasibility_reviews'] = [{k: latest[k] for k in ('context', 'assessments', 'limitations')}]
    return dict(project_id=project['project_id'], state_hash=state_hash(state, path, root),
                recommended_option_id=project.get('recommended_option_id'),
                option_ids=[o['option_id'] for o in project['options']],
                evidence_ids=[e['evidence_id'] for e in project['evidence']],
                source_ids=[s['source_id'] for s in project['sources']],
                source_content={s['source_id']: source_version(project, s,
                                path.parent if project.get('path_base') == 'project' else root)
                                for s in project['sources']},
                snapshot={'objective': project['objective'], 'constraints': copy.deepcopy(project.get('constraints', []))})


def dependency_impact(project, source_ids, evidence_ids, option_ids=()):
    from checkpoint import impacted
    seeds = set(evidence_ids)
    marked = [dict(e, source_ids=e['source_ids'] + (['__stress_seed__'] if e['evidence_id'] in seeds else []))
              for e in project['evidence']]
    evidence, options = impacted({'evidence': marked, 'options': project['options']},
                                 set(source_ids) | {'__stress_seed__'})
    return {'evidence_ids': evidence, 'option_ids': sorted(set(options) | set(option_ids))}


def affected(project, scenario, review):
    assumptions = {a['assumption_id']: a for a in review['assumptions']}
    direct_options = {oid for aid in scenario['assumption_ids'] for oid in assumptions[aid]['option_ids']}
    return {**dependency_impact(project, scenario['changed_source_ids'], scenario['changed_evidence_ids'], direct_options),
            'constraint_changes': scenario['constraint_changes']}


def inspect(project, path, root):
    reviews = project.get('decision_stress_tests', [])
    if not reviews:
        return {'status': 'not_recorded', 'blockers': [], 'scenarios': []}
    review = reviews[-1]
    comparison = comparison_context(review)
    current = baseline(project, path, root)
    if review['baseline'] != current:
        old = review['baseline']
        old_content = old.get('source_content', {})
        changed_sources = sorted(sid for sid in set(old_content) | set(current['source_content'])
                                 if old_content.get(sid) != current['source_content'].get(sid))
        constraints_changed = old['snapshot'].get('constraints') != current['snapshot'].get('constraints')
        # Constraints have no structured per-evidence IDs in legacy projects.
        # Conservatively request review of all registered assumption dependencies.
        eids = {eid for a in review['assumptions'] for eid in a['evidence_ids']} if constraints_changed else set()
        oids = {oid for a in review['assumptions'] for oid in a['option_ids']} if constraints_changed else set()
        return {'status': 'stale', 'review_id': review['review_id'],
                'comparison': comparison,
                'blockers': ['Decision stress review is stale: constraints, recommendation, strategy or source/evidence content changed'],
                'changed_source_ids': changed_sources,
                'impact': dependency_impact(project, changed_sources, eids, oids),
                'context_changes': {k: {'before': old['snapshot'].get(k), 'after': current['snapshot'].get(k)}
                                    for k in ('objective', 'constraints') if old['snapshot'].get(k) != current['snapshot'].get(k)},
                'scenarios': [], 'action': 'Prepare a new review; keep the historical record. Do not apply old conditional conclusions.'}
    blockers, results = [], []
    evidence = {e['evidence_id']: e for e in project['evidence']}
    # Existing provenance checks are reused, not replaced with invented confidence scores.
    relevant_evidence = {eid for a in review['assumptions'] for eid in a['evidence_ids']}
    for s in review['scenarios']:
        relevant_evidence.update(s['evidence_ids'])
        relevant_evidence.update(s['recommendation']['evidence_ids'])
        for item in s['option_impacts']:
            relevant_evidence.update(item['evidence_ids'])
    from quality import support_blockers
    blockers.extend(support_blockers(project, path, root, relevant_evidence, 'Stress support'))
    for scenario in review['scenarios']:
        if scenario['premise_status'] == 'observed' and any(evidence[eid]['claim_type'] not in ('source_fact', 'measured_fact', 'association', 'qualitative_signal')
                                                          for eid in scenario['evidence_ids']):
            blockers.append('Observed scenario cannot rely on a hypothesis/forecast: ' + scenario['scenario_id'])
        decision = scenario['recommendation']
        impact = affected(project, scenario, review)
        decision_support = set(decision['evidence_ids'])
        pending = list(decision_support)
        while pending:
            for ref in evidence[pending.pop()].get('related_evidence_ids', []):
                if ref not in decision_support:
                    decision_support.add(ref)
                    pending.append(ref)
        if decision['outcome'] in ('keep', 'switch', 'conditional_option') and decision_support.intersection(impact['evidence_ids']):
            blockers.append('Scenario preference relies on an invalidated premise; obtain alternative support: ' + scenario['scenario_id'])
        if decision['outcome'] in ('keep', 'switch', 'conditional_option') and not any(evidence[eid]['claim_type'] in ('source_fact', 'measured_fact', 'association', 'qualitative_signal')
                                                               for eid in decision['evidence_ids']):
            blockers.append('Conditional preference needs more than hypotheses: ' + scenario['scenario_id'])
        results.append({'scenario_id': scenario['scenario_id'], 'premise_status': scenario['premise_status'],
                        'impact': impact, 'conditional_recommendation': decision})
        estimates = [{'option_id':row['option_id'], **copy.deepcopy(row['provisional_assessment'])}
                     for row in scenario['option_impacts'] if row.get('provisional_assessment')]
        if estimates: results[-1]['provisional_assessments'] = estimates
    return {'status': 'blocked' if blockers else 'review_record_complete', 'review_id': review['review_id'],
            'comparison': comparison,
            'blockers': sorted(set(blockers)), 'scenarios': results,
            'note': 'Conditional model review, not a prediction, semantic truth check or human choice. Project recommendation is never changed by this tool.'}


def comparison_context(review):
    original = review['baseline']['recommended_option_id']
    return {'status': 'no_baseline_recommendation' if original is None else 'baseline_recommendation_recorded',
            'recommended_option_id': original,
            'note': ('Базовая рекомендация отсутствует: сценарии сравнивают доступные варианты и ограничения; '
                     'сравнение с базовой рекомендацией невозможно. Условный вариант не создаёт рекомендацию проекта.'
                     if original is None else
                     'Сценарии условно сравниваются с исходной рекомендацией ' + original + '; это не выбор человека.')}


def markdown(project, status):
    lines = ['## Проверка решения на прочность', '', 'Статус разбора: ' + status['status']]
    if not project.get('decision_stress_tests'):
        return '\n'.join(lines + ['Разбор не записан.']) + '\n'
    review = project['decision_stress_tests'][-1]
    comparison = comparison_context(review)
    lines += ['Версия: ' + review['review_id'], comparison['note'],
              'Основание версии: ' + review['baseline']['state_hash'], 'Проверил: ' + review['reviewer'],
              '', 'Условный разбор; сценарии не являются прогнозами. Выбор человека не меняется.',
              'Ограничения: ' + review['limitations'], 'Сильнейшее возражение: ' + review['strongest_objection'],
              'Условие пересмотра: ' + review['reversal_condition'], '', '### Ключевые допущения']
    for a in review['assumptions']:
        lines += [f"- {a['assumption_id']} [{a['basis']}]: {a['statement']}",
                  f"  Варианты: {', '.join(a['option_ids'])}; основания: {', '.join(a['evidence_ids']) or 'нет'}.",
                  '  Проверить: ' + a['verification_needed']]
    if status['blockers']:
        lines += ['', '### Требуется пересмотр', *['- ' + b for b in status['blockers']]]
        if status.get('context_changes'):
            lines += ['Изменения: ' + json.dumps(status['context_changes'], ensure_ascii=False)]
        if status.get('impact'):
            lines += ['Повторно оценить: ' + json.dumps(status['impact'], ensure_ascii=False)]
    # Historical scenarios remain visible, but never present stale output as current.
    lines += ['', 'Ниже сохранённая версия; при stale/blocked её выводы применять нельзя.']
    impacts = {s['scenario_id']: s['impact'] for s in status['scenarios']}
    for s in review['scenarios']:
        lines += ['', '### ' + s['scenario_id'] + ': ' + s['title'],
                  'Предпосылка [' + s['premise_status'] + ']: ' + s['premise']]
        for change in s['constraint_changes']:
            lines += ['Изменение ограничения: ' + change['before'] + ' → ' + change['after']]
        if s['scenario_id'] in impacts:
            lines += ['Затронутые записи: ' + json.dumps(impacts[s['scenario_id']], ensure_ascii=False)]
        for item in s['option_impacts']:
            lines += [f"- {item['option_id']}: {item['feasibility']}; {item['preference']}. {item['reason']}",
                      '  Основания: ' + (', '.join(item['evidence_ids']) or 'нет; условное рассуждение')]
            if item.get('provisional_assessment'):
                estimate = item['provisional_assessment']
                label = {'likely_feasible':'предположительно осуществимо',
                         'likely_infeasible':'предположительно неосуществимо',
                         'undetermined':'для предположения пока недостаточно оснований'}[estimate['verdict']]
                lines += ['  Предварительная оценка: ' + label + '; ресурс не подтверждён.',
                          '  Допущения: ' + ', '.join(estimate['assumption_ids']) + '. ' + estimate['rationale'],
                          '  Проверить: ' + estimate['check_next']]
        d = s['recommendation']
        lines += ['Условный итог: ' + d['outcome'] + '; вариант: ' + str(d['option_id']),
                  d['rationale'], 'Основания итога: ' + (', '.join(d['evidence_ids']) or 'нет'),
                  'Новые данные: ' + s['new_data_needed'], 'Пересмотреть когда: ' + s['review_trigger']]
    return '\n'.join(lines) + '\n'


def prepare(project, path, root, review_id):
    if project.get('recommended_option_id') is not None and not nonempty(project.get('recommendation_rationale')):
        raise ValueError('An existing recommendation requires its rationale')
    strategy = project.get('strategy_review', {})
    return {'schema_version': 1, 'review_id': review_id, 'baseline': baseline(project, path, root),
            'reviewer': '', 'strongest_objection': strategy.get('strongest_objection', ''),
            'reversal_condition': strategy.get('reversal_condition', ''), 'limitations': '',
            'assumptions': [{'assumption_id': 'A1', 'statement': '', 'basis': 'hypothesis',
                             'evidence_ids': [], 'option_ids': [], 'verification_needed': ''}],
            'scenarios': [{'scenario_id': f'SC{i}', 'title': '', 'premise': '', 'premise_status': 'hypothetical',
                           'assumption_ids': ['A1'], 'evidence_ids': [], 'changed_source_ids': [],
                           'changed_evidence_ids': [], 'constraint_changes': [],
                           'option_impacts': [{'option_id': o['option_id'], 'feasibility': 'uncertain',
                                              'preference': 'undetermined', 'reason': '', 'evidence_ids': []}
                                             for o in project['options']],
                           'recommendation': {'outcome': 'insufficient_evidence', 'option_id': None,
                                              'rationale': '', 'evidence_ids': []},
                           'new_data_needed': '', 'review_trigger': ''} for i in (1, 2)]}


def record_review(project, path, root, review, *, field, inspector, action, tool):
    from checkpoint import write_state
    from validate_project import validate
    from ledger import append, read_entries, ledger_path, verify
    candidate = copy.deepcopy(project)
    candidate.setdefault(field, []).append(copy.deepcopy(review))
    errors = validate(candidate)
    if errors:
        raise ValueError('; '.join(errors))
    result = inspector(candidate, path, root)
    if result['status'] != 'review_record_complete':
        raise ValueError('; '.join(result['blockers']))
    # Fail before changing state if the existing action log is damaged.
    if verify(read_entries(ledger_path(path))):
        raise ValueError('Damaged ledger; review it before saving')
    if json.loads(path.read_text(encoding='utf-8-sig')) != project:
        raise ValueError('Project changed during review; reload and reassess before recording')
    candidate[field][-1]['recorded_at'] = datetime.now(timezone.utc).isoformat(timespec='seconds')
    write_state(path, candidate)
    try:
        append(path, {'step': project['stage'], 'action': action + ': ' + review['review_id'],
                      'status': 'done', 'actor': 'script', 'tool': tool,
                      'note': 'Recorded review; no automatic strategy change or human choice. Time/cost unknown.'})
    except (OSError, ValueError) as error:
        raise ValueError('Review saved but ledger append failed; inspect state before retrying: ' + str(error)) from error
    return result


def record(project, path, root, review):
    return record_review(project, path, root, review, field='decision_stress_tests',
                         inspector=inspect, action='decision stress review', tool='scripts/stress_test.py')


def main():
    from checkpoint import ROOT
    from output_guard import check_output
    from project_tool import load
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('command', choices=('prepare', 'record', 'inspect', 'report'))
    parser.add_argument('project', type=Path)
    parser.add_argument('--review-id')
    parser.add_argument('--review', type=Path)
    parser.add_argument('--out', type=Path)
    args = parser.parse_args()
    try:
        path = args.project.resolve()
        project = load(path)
        if args.command == 'record':
            if not args.review or args.out:
                raise ValueError('record needs --review and does not accept --out')
            result = record(project, path, ROOT, json.loads(args.review.read_text(encoding='utf-8-sig')))
        elif args.command == 'prepare':
            if not args.review_id:
                raise ValueError('prepare needs --review-id')
            result = prepare(project, path, ROOT, args.review_id)
        else:
            result = inspect(project, path, ROOT)
        output = markdown(project, result) if args.command == 'report' else json.dumps(result, ensure_ascii=False, indent=2)
        if args.out:
            check_output(project, path, args.out)
            if args.out.exists():
                raise ValueError('Output exists; use a new versioned filename')
            args.out.parent.mkdir(parents=True, exist_ok=True)
            args.out.write_text(output + '\n', encoding='utf-8')
        else:
            print(output)
        return 1 if args.command in ('inspect', 'report') and result['blockers'] else 0
    except (OSError, ValueError, KeyError, TypeError) as error:
        parser.exit(1, f'Stress test: {error}\n')


if __name__ == '__main__':
    sys.exit(main())
